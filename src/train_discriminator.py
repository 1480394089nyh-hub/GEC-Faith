# -*- coding: utf-8 -*-
"""
train_discriminator.py -- Train the "correction faithfulness discriminator" (binary / 5-class).

Data: results/discriminator/{train,val,test}.jsonl + label_map.json, generated by
      scripts/prepare_train_data.py.
Base model: hfl/chinese-roberta-wwm-ext by default (override with --model).
Input format: `[CLS] original [SEP] correction [SEP]` (sentence-pair classification).

Usage (cloud GPU):
    # binary (faithful / unfaithful)
    python src/train_discriminator.py --task bin
    # 5-class (faithful-correct / missed / semantic-drift / over-correction / hallucination)
    python src/train_discriminator.py --task multi

Outputs (results/discriminator/{bin|multi}/):
    best_model/                -- best checkpoint (selected by val macro-F1)
    test_predictions.csv       -- per-example test predictions (utf-8-sig, Excel-friendly)
    test_metrics.md            -- full test metrics (per-class P/R/F1 + confusion matrix)
    train_log.jsonl            -- per-epoch loss + val metrics (traceable)
"""
import argparse
import json
import os
from collections import Counter

import numpy as np
import torch
from sklearn.metrics import (accuracy_score, classification_report,
                             confusion_matrix, f1_score)
from torch.utils.data import Dataset
from transformers import (AutoModelForSequenceClassification, AutoTokenizer,
                          Trainer, TrainingArguments, set_seed)

DATA_DIR = "results/discriminator"
DEFAULT_MODEL = "hfl/chinese-roberta-wwm-ext"
SEED = 42


class PairDataset(Dataset):
    def __init__(self, path, tokenizer, max_len, label_key):
        self.items = [json.loads(l) for l in open(path, encoding="utf-8") if l.strip()]
        self.tokenizer = tokenizer
        self.max_len = max_len
        self.label_key = label_key  # "label_bin_id" or "label5_id"

    def __len__(self):
        return len(self.items)

    def __getitem__(self, i):
        it = self.items[i]
        enc = self.tokenizer(
            it["src"], it["hyp"],
            max_length=self.max_len, truncation=True, padding="max_length",
        )
        return {
            "input_ids": torch.tensor(enc["input_ids"], dtype=torch.long),
            "attention_mask": torch.tensor(enc["attention_mask"], dtype=torch.long),
            "labels": torch.tensor(it[self.label_key], dtype=torch.long),
        }


def compute_metrics(eval_pred):
    logits, labels = eval_pred
    preds = np.argmax(logits, axis=-1)
    return {
        "accuracy": accuracy_score(labels, preds),
        "macro_f1": f1_score(labels, preds, average="macro", zero_division=0),
        "weighted_f1": f1_score(labels, preds, average="weighted", zero_division=0),
    }


class WeightedTrainer(Trainer):
    """Trainer with per-class weights (native Trainer does not support per-class weight)."""
    def __init__(self, class_weights, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.class_weights = class_weights

    def compute_loss(self, model, inputs, return_outputs=False, num_items_in_batch=None):
        labels = inputs.pop("labels")
        outputs = model(**inputs)
        logits = outputs.logits
        w = self.class_weights.to(logits.device)
        loss = torch.nn.functional.cross_entropy(logits, labels, weight=w)
        return (loss, outputs) if return_outputs else loss


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--task", required=True, choices=["bin", "multi"],
                    help="bin = faithful/unfaithful binary; multi = 5 failure types")
    ap.add_argument("--model", default=DEFAULT_MODEL)
    ap.add_argument("--data_dir", default=DATA_DIR)
    ap.add_argument("--max_len", type=int, default=256)
    ap.add_argument("--epochs", type=int, default=5)
    ap.add_argument("--batch_size", type=int, default=32)
    ap.add_argument("--lr", type=float, default=2e-5)
    ap.add_argument("--seed", type=int, default=SEED)
    ap.add_argument("--output_dir", default=None, help="default results/discriminator/{task}")
    args = ap.parse_args()

    set_seed(args.seed)

    label_key = "label_bin_id" if args.task == "bin" else "label5_id"
    label_name = "label_bin" if args.task == "bin" else "label5"
    n_labels = 2 if args.task == "bin" else 5

    label_map = json.load(open(os.path.join(args.data_dir, "label_map.json"), encoding="utf-8"))
    id2label = {int(k): v for k, v in
                (label_map["id2label_bin"] if args.task == "bin" else label_map["id2label5"]).items()}

    out_dir = args.output_dir or os.path.join(args.data_dir, args.task)
    os.makedirs(out_dir, exist_ok=True)

    print(f"[info] task={args.task}  labels={n_labels}  model={args.model}  max_len={args.max_len}")
    print(f"[info] output={out_dir}")

    tokenizer = AutoTokenizer.from_pretrained(args.model, use_fast=False)
    model = AutoModelForSequenceClassification.from_pretrained(
        args.model, num_labels=n_labels,
        id2label=id2label, label2id={v: k for k, v in id2label.items()},
    )

    train_ds = PairDataset(os.path.join(args.data_dir, "train.jsonl"), tokenizer, args.max_len, label_key)
    val_ds = PairDataset(os.path.join(args.data_dir, "val.jsonl"), tokenizer, args.max_len, label_key)
    test_ds = PairDataset(os.path.join(args.data_dir, "test.jsonl"), tokenizer, args.max_len, label_key)

    # Class weights = inverse frequency, capped at 10 to keep the rare "hallucination"
    # class (7 in train) from over-weighting and destabilizing training.
    counts = Counter(json.loads(l)[label_key]
                     for l in open(os.path.join(args.data_dir, "train.jsonl"), encoding="utf-8") if l.strip())
    class_weights = torch.tensor(
        [min(10.0, len(train_ds) / (n_labels * counts.get(c, 1))) for c in range(n_labels)],
        dtype=torch.float,
    )
    print("[info] class weights: " + ", ".join(f"{id2label[i]}={class_weights[i].item():.2f}" for i in range(n_labels)))

    # Warmup steps = total steps * 10% (transformers 5.x removed warmup_ratio; use warmup_steps).
    steps_per_epoch = -(-len(train_ds) // args.batch_size)  # ceil
    warmup_steps = max(0, int(0.1 * steps_per_epoch * args.epochs))

    training_args = TrainingArguments(
        output_dir=os.path.join(out_dir, "checkpoints"),
        num_train_epochs=args.epochs,
        per_device_train_batch_size=args.batch_size,
        per_device_eval_batch_size=args.batch_size,
        learning_rate=args.lr,
        weight_decay=0.01,
        warmup_steps=warmup_steps,
        eval_strategy="epoch",
        save_strategy="epoch",
        save_total_limit=1,
        load_best_model_at_end=True,
        metric_for_best_model="macro_f1",
        greater_is_better=True,
        logging_steps=10,
        seed=args.seed,
        report_to=[],
    )

    trainer = WeightedTrainer(
        class_weights=class_weights,
        model=model,
        args=training_args,
        train_dataset=train_ds,
        eval_dataset=val_ds,
        compute_metrics=compute_metrics,
    )

    print("[info] starting training ...")
    trainer.train()

    best_dir = os.path.join(out_dir, "best_model")
    trainer.save_model(best_dir)
    tokenizer.save_pretrained(best_dir)

    with open(os.path.join(out_dir, "train_log.jsonl"), "w", encoding="utf-8") as f:
        for entry in trainer.state.log_history:
            f.write(json.dumps(entry, ensure_ascii=False) + "\n")

    # ---- test evaluation ----
    preds, labels, _ = trainer.predict(test_ds)
    pred_ids = np.argmax(preds, axis=-1)
    labels = labels.astype(int)

    cm = confusion_matrix(labels, pred_ids, labels=list(range(n_labels)))
    report = classification_report(
        labels, pred_ids, labels=list(range(n_labels)),
        target_names=[id2label[i] for i in range(n_labels)],
        zero_division=0, output_dict=True,
    )

    with open(os.path.join(out_dir, "test_predictions.csv"), "w", encoding="utf-8-sig") as f:
        f.write("序号,句子序号,模型,原句,改句,真实标签,预测标签\n")
        for it, p in zip(test_ds.items, pred_ids):
            f.write(",".join([str(it["id"]), str(it["sent_idx"]), it["model"],
                              it["src"], it["hyp"], it[label_name], id2label[int(p)]]) + "\n")

    md = []
    md.append(f"# 判别器 test 指标（task={args.task}）\n")
    md.append(f"> 模型：`{args.model}`　{n_labels} 分类　max_len={args.max_len}　epochs={args.epochs}　"
              f"batch={args.batch_size}　lr={args.lr}　seed={args.seed}\n")
    md.append(f"> 数据：train/val/test = {len(train_ds)}/{len(val_ds)}/{len(test_ds)}　"
              f"类别权重（逆频率，上限10）：" + "，".join(f"{id2label[i]}={class_weights[i].item():.2f}" for i in range(n_labels)) + "\n")
    md.append("\n## 总指标\n")
    md.append(f"- Accuracy = {accuracy_score(labels, pred_ids):.4f}")
    md.append(f"- Macro-F1 = {f1_score(labels, pred_ids, average='macro', zero_division=0):.4f}")
    md.append(f"- Weighted-F1 = {f1_score(labels, pred_ids, average='weighted', zero_division=0):.4f}\n")
    md.append("\n## 逐类 P / R / F1\n")
    md.append("| 标签 | Precision | Recall | F1 | 支持数 |")
    md.append("|---|---|---|---|---|")
    for i in range(n_labels):
        d = report[id2label[i]]
        md.append(f"| {id2label[i]} | {d['precision']:.4f} | {d['recall']:.4f} | {d['f1-score']:.4f} | {int(d['support'])} |")
    md.append("\n## 混淆矩阵（行=真实，列=预测）\n")
    md.append("| 真实\\预测 | " + " | ".join(id2label[i] for i in range(n_labels)) + " |")
    md.append("|---|" + "---|" * n_labels)
    for i in range(n_labels):
        md.append(f"| {id2label[i]} | " + " | ".join(str(cm[i][j]) for j in range(n_labels)) + " |")

    with open(os.path.join(out_dir, "test_metrics.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(md) + "\n")

    print("\n".join(md))
    print(f"\n[info] all outputs saved to {out_dir}: best_model/ test_predictions.csv test_metrics.md train_log.jsonl")


if __name__ == "__main__":
    main()
